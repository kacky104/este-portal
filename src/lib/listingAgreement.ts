export function agreementBodyText(): string {
  const lines: string[] = [];
  lines.push(AGREEMENT_TITLE, `${AGREEMENT_OPERATOR} 御中`, '', AGREEMENT_LEAD, '');
  lines.push('【掲載規約】');
  AGREEMENT_TERMS.forEach((t, i) => lines.push(`${i + 1}. ${t.title}：${t.body}`));
  lines.push(AGREEMENT_PRIVACY_NOTE, '');
  lines.push('【重要事項】');
  AGREEMENT_IMPORTANT.forEach((t) => lines.push(`● ${t}`));
  lines.push('', '【誓約事項】');
  AGREEMENT_PLEDGES.forEach((t, i) => lines.push(`${i + 1}. ${t}`));
  lines.push('');
  AGREEMENT_NOTES.forEach((t) => lines.push(`※ ${t}`));
  lines.push('', AGREEMENT_VERSION_LABEL);
  return lines.join('\n');
}

/** 入力の決まり（★ 画面とサーバーの両方で同じものを使う） */
export type AgreementInput = {
  salonName: string;
  address: string;
  phone: string;
  email: string;
  companyName: string; // 法人名（任意）
  representative: string; // 代表者名（必須）
};

export function normalizeAgreementInput(raw: Partial<AgreementInput>): AgreementInput {
  const s = (v: unknown, max: number) => String(v ?? '').replace(/\s+/g, ' ').trim().slice(0, max);
  return {
    salonName: s(raw.salonName, 100),
    address: s(raw.address, 200),
    phone: s(raw.phone, 30),
    email: s(raw.email, 200),
    companyName: s(raw.companyName, 100),
    representative: s(raw.representative, 60),
  };
}

/** 足りないものがあれば、その説明を返す（無ければ null） */
export function agreementInputError(v: AgreementInput): string | null {
  if (!v.representative) return '代表者名を入れてください';
  if (!v.salonName) return '店舗名を入れてください';
  if (!v.address) return '所在地を入れてください';
  if (!v.phone) return '電話番号を入れてください';
  if (!/^[0-9０-９+\-ー－() （）]{6,}$/.test(v.phone)) return '電話番号を確かめてください';
  if (!v.email) return 'メールアドレスを入れてください';
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v.email)) return 'メールアドレスを確かめてください';
  return null;
}
