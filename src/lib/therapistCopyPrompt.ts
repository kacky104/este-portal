/**
 * ★★★ seed から【決まった組み合わせ】のお手本を選ぶ。★ 純粋関数・毎回同じ結果。
 *
 * ★★ persona が重ならないように選ぶ。★ ここが肝。
 *   ★ ただ無作為に3本選ぶと「癒し・癒し・穏やか」になりうる。★ それでは直らない。
 * ★ seed が読めない値でも落ちない（0 として扱う）。★ count が本数を超えても落ちない。
 */
export function pickSamples(seed: number, count: number = SAMPLES_PER_CALL): CopySample[] {
  const n = SAMPLE_LIST.length;
  if (n === 0) return [];
  const k = Math.max(1, Math.min(Math.trunc(count) || 1, n));
  const raw = Math.trunc(Number(seed));
  const base = Number.isFinite(raw) ? Math.abs(raw) : 0;

  // ★ seed から決まった数の並びを作る。★ 同じ seed なら毎回まったく同じ（点検で固定できる）
  //
  // ★★★ ここで2回つまずいた（第126便・2026-09-04）。★ どちらも「散らしたつもり」で偏った。
  //   ① persona を【ずらす】だけ → 連続した3つしか出ず、組み合わせが6種類しかなかった
  //   ② 線形合同法 ＋ `r % n` → **下位ビットは周期が短く偏る**。★ 「年上」だけ9回（他は23〜42回）
  //   → xorshift（全ビットが均等）にして、余りではなく【上位ビット】から取る。
  //   ★★ 乱数は「それらしく見える」だけでは足りない。★ 必ず数えて確かめる（点検に入れてある）。
  let r = (Math.imul(base + 1, 2654435761) >>> 0) || 1; // ★ 0 だと xorshift が動かない
  const next = (mod: number): number => {
    r ^= (r << 13) >>> 0; r >>>= 0;
    r ^= r >>> 17;
    r ^= (r << 5) >>> 0; r >>>= 0;
    // ★ 余り（下位ビット）ではなく、0〜1 に直してから掛ける（上位ビットが効く）
    return mod > 0 ? Math.floor((r / 4294967296) * mod) : 0;
  };

  // ★★★ persona の順番を【入れ替える】。★ ずらすだけでは足りない（第126便で実測）。
  //   ★ 最初は (seed + i) % 6 でずらしていたが、それだと **連続した3つ**しか選ばれず、
  //     101人に対して組み合わせが【6種類】しか出なかった。★ 6本から3本なら20通りあるのに。
  //   ★★ 「散らしたつもり」で偏ることがある。★ 種類を数えて確かめる（点検に入れた）。
  const personas = [...new Set(SAMPLE_LIST.map((x) => x.persona))];
  for (let i = personas.length - 1; i > 0; i--) {
    const j = next(i + 1);
    [personas[i], personas[j]] = [personas[j], personas[i]];
  }

  const out: CopySample[] = [];
  const used = new Set<number>();
  // ★ 先頭の persona から1本ずつ。★ 一周して足りなければもう一周（persona より多く要るとき）
  for (let round = 0; out.length < k && round < n + 1; round++) {
    for (let i = 0; i < personas.length && out.length < k; i++) {
      const p = personas[i];
      const idx = SAMPLE_LIST
        .map((x, j) => (x.persona === p && !used.has(j) ? j : -1))
        .filter((j) => j >= 0);
      if (idx.length === 0) continue;
      const chosen = idx[next(idx.length)];
      used.add(chosen);
      out.push(SAMPLE_LIST[chosen]);
    }
  }
  return out;
}

