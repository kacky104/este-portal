// 駅ちか → フクエスの「当日の出勤」の取り込み間隔（第1312便・2026-10-08・カッキーさんの決定）。
//
// ★★★ 15分 → 30分。駅ちかへの負荷（公開ページの読み）を半分にするため。
//   ★ 週間出勤（7日分）は今までどおり1日1回（朝の full の周）。★ VPS の crontab（15分ごと）は変えない。
//     店ごとの間隔（salon_import_sources.import_interval_min）を満たさない店は /api/import/targets が返さないので、
//     crontab が15分ごとに起きても、駅ちかを読むのは30分に1回になる。
//   ★ 当日の周では、出勤のほか【駅ちかの即ヒメ → フクエスの今すぐ】・新しく入った方の作成も一緒に取り込む（＝最大30分遅れる）。

/** 新しく登録する店の当日の取り込み間隔（分）。★ 運営の「取り込み元の登録」がこの値で立てる */
export const IMPORT_LIST_INTERVAL_MIN = 30;

/** VPS の停止（駅ちかが 5xx を返したとき・import.sh のサーキットブレーカー）で止まる長さ（分） */
const IMPORT_5XX_PAUSE_MIN = 10;

/**
 * 取り込みで立てた「今すぐ」の保険の期限（分）。
 *   ★ ふだんは次の周で「即ヒメでなくなった方」を落とすので、この期限は見え方に関係しない。
 *   ★ 取り込みが止まったとき（5xx の停止など）に、今すぐが一斉に0人にならない長さ:
 *     最後に成功した周（最大1間隔前）＋停止10分＋次の周まで最大1間隔＋余裕10分。
 *   ★ 第636便で15分間隔のとき50分にした。30分間隔では 30＋10＋30＋10＝80分。
 */
export const IMASUGU_IMPORT_MINUTES = IMPORT_LIST_INTERVAL_MIN * 2 + IMPORT_5XX_PAUSE_MIN + 10;
