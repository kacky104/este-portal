// エステ魂の写メ日記の「いまどうなっているか」を数える（第141便・2026-09-04）。
// ★ 純粋関数（禁則180）。★ DBもネットワークも触らない。
//
// ★★★ なぜ要るか
//   2026-09-04 に自動反映が動きはじめたが、店舗様が結果を見られるのは
//   「連携の記録」の細かい行だけだった。★ 1回の送信で7行並ぶので、そこから探せない。
//   → **数だけ**を1か所にまとめて出す（カッキーさんの判断・2026-09-04）。
//
// ★★★ ここで【出さない】と決めたもの
//   ・相手側の利用状況（魂セラピストを始めているか）
//       ★ 知るには魂セラピスト一覧を読む＝ログインが要る。★ 画面を開くたびに相手を叩かない。
//       ★★ 分からないものを数に混ぜない。★ 代わりに「お送りするときに確かめます」と書く。
//   ・誰が送れないかの名前
//       ★ 「数だけ」と決めた。★ 名前まで出すのは次の便（人ごとの一覧）。

export type DiaryStatusInput = {
  /** 在籍の人数（is_active） */
  在籍: number;
  /** 了承ありの人数 */
  了承あり: number;
  /** 了承あり かつ 名簿が結びついている人数 */
  了承あり結びあり: number;
  /** 送れた件数（state='sent'） */
  送れた: number;
  /** 送れていない件数（state='failed'） */
  送れていない: number;
  /** 判定できなかった件数（state='unknown'） */
  判定できず: number;
  /** 最後に送れた時刻（ISO）。★ 無ければ null */
  最後に送れた: string | null;
};

export type DiaryStatus = {
  送れた: number;
  送れていない: number;
  判定できず: number;
  最後に送れた: string | null;
  /** 人の内訳（★ 合計は必ず在籍と一致する） */
  人: { 在籍: number; 送れる見込み: number; 了承がまだ: number; 名簿が未結び: number };
};

/**
 * ★★ 数を整える。★ ここで【つじつまを合わせる】。
 *   ★ 了承あり ≧ 了承あり結びあり を守る（★ 逆転した数を画面に出さない）。
 *   ★ 3つの人数の合計が在籍と一致するようにする（★ 足して合わない表を出さない）。
 */
export function buildDiaryStatus(input: DiaryStatusInput): DiaryStatus {
  const n = (v: number) => (Number.isFinite(v) && v > 0 ? Math.trunc(v) : 0);
  const 在籍 = n(input.在籍);
  // ★ 了承ありが在籍を超えることは無い（退職した人の記録が残っていても数えない）
  const 了承あり = Math.min(n(input.了承あり), 在籍);
  // ★ 結びありが了承ありを超えることも無い
  const 結び = Math.min(n(input.了承あり結びあり), 了承あり);
  return {
    送れた: n(input.送れた),
    送れていない: n(input.送れていない),
    判定できず: n(input.判定できず),
    最後に送れた: input.最後に送れた ?? null,
    人: {
      在籍,
      送れる見込み: 結び,
      了承がまだ: 在籍 - 了承あり,
      // ★ 了承はあるが結びが無い人
      名簿が未結び: 了承あり - 結び,
    },
  };
}

/**
 * ★★ 店舗様が読む1行。★ 0でも「送れる見込み」は必ず出す（第35便の反省6）。
 * ★ 「送れる見込み」と書くのは、**相手の利用状況をまだ見ていない**から。
 *   ★★ 「送れます」と言い切らない。★ 言い切って送れなかったら、そちらのほうが困る。
 */
export function diaryStatusLine(s: DiaryStatus): string {
  const p = s.人;
  const parts = ['お送りできる見込み ' + p.送れる見込み + '名'];
  if (p.了承がまだ > 0) parts.push('ご了承がまだ ' + p.了承がまだ + '名');
  if (p.名簿が未結び > 0) parts.push('名簿が未結び ' + p.名簿が未結び + '名');
  return parts.join(' ／ ') + '（在籍 ' + p.在籍 + '名）';
}

/**
 * ★★★ 送信の結果の1行。★ 「送った」と「載った」を混ぜない。
 * ★ 0件のときも「まだお送りしていません」と書く（★ 空欄にしない）。
 */
export function diarySentLine(s: DiaryStatus): string {
  if (s.送れた === 0 && s.送れていない === 0 && s.判定できず === 0) {
    return 'まだお送りしていません';
  }
  const parts = ['お送りしました ' + s.送れた + '件'];
  // ★ 0のものは並べない。★ ただし「送れていない」は0でも出す（★ 見落とさせない）
  parts.push('お送りできませんでした ' + s.送れていない + '件');
  if (s.判定できず > 0) parts.push('★ 結果を確かめられなかった ' + s.判定できず + '件');
  return parts.join(' ／ ');
}

/** ★ 店舗様に次にしてもらうこと。★ 何もなければ null（「異常なし」の行を作らない）。 */
export function diaryNextStep(s: DiaryStatus): string | null {
  if (s.判定できず > 0) {
    return '結果を確かめられなかった写メ日記があります。エステ魂のページで、掲載されているかご確認ください';
  }
  if (s.送れていない > 0) {
    return 'お送りできなかった写メ日記があります。しばらく置いて自動でもう一度お送りします';
  }
  // ★★★ 順番に意味がある（★ 点検で気づいて入れ替えた）:
  //   「ご了承はいただいたのに、名簿が結びついていないので送れない」ほうを先に出す。
  //   ★ あと1手で送れる状態。★ まだ聞いていない方に聞いて回るより早い。
  //   ★★ 逆にすると、了承済みの方がずっと送られないまま埋もれる。
  if (s.人.送れる見込み === 0 && s.人.名簿が未結び > 0) {
    return 'ご了承をいただいた方がいます。セラピスト一覧で、エステ魂の登録と結びつけてください';
  }
  if (s.人.送れる見込み === 0 && s.人.了承がまだ > 0) {
    return 'ご本人に確認のうえ、「エステ魂へ送ってよい」を記録してください';
  }
  return null;
}
