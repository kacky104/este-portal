/** 同意が要るか。★ 版が違えば取り直す（null＝一度も同意していない）。 */
export function needsConsent(savedVersion: string | null | undefined): boolean {
  return savedVersion !== MEDIA_CONSENT_VERSION;
}

/** 監査ログや控えに残すための、文言の全文（1つの文字列）。 */
export function consentFullText(): string {
  return MEDIA_CONSENT_SECTIONS.map((s, i) => `${i + 1}. ${s.heading}\n${s.body}`).join('\n\n');
}
