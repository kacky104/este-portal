/**
 * ★★★ 「言い方を直しただけの版」（第89便・カッキーさんの指摘）。
 *
 * ★ きっかけ: ボタン名を直したので同意文の中の名前も直し、作法どおり版を上げた。
 *   ★★ すると【何も知らせないまま】接続テストと送信が止まった。
 *     取り直しの場所はカードを開いて一番下までスクロールしないと出てこない。
 *   ★★★ 店舗様から見れば「昨日まで送れていたのに、理由も出ずに止まった」。
 *     ★ 店舗が選んでいない結果を、失敗として黙って起こしている（§223・第87便と同じ形）。
 *
 * ★★★ そこで【まだ同意していない】と【古い版に同意している】を1つにしない。
 *   ★ 引き継ぎメモ 3-5「0件と分からないを混ぜない」の、同意版の版。
 *   ★ 記録には同意した版がそのまま残るので、どの文言に同意したかは追える。
 *
 * ★★★ ここに足してよいのは【お預かりするもの・使い道・届く範囲・保管の仕方が
 *   1つも変わっていない】ときだけ。★ 1つでも変わったら足さない。
 *   ★★ 迷ったら足さない（取り直させる側に倒す）。
 * ★★ 版を上げるたびに【作り直す】。★ 前の版を機械的に足していかない。
 *   ★ 足していくと、預かるものが変わった日に、誰も取り直さなくなる。
 */
export const MEDIA_CONSENT_WORDING_ONLY: readonly string[] = [
  'v1-2026-08-27',   // → v3: ボタン名を直しただけ（預かるもの・使い道は変わっていない）
  'v2-2026-08-31',   // → v3: 同意文からボタン名を外しただけ
];

/**
 * 同意が要るか。
 * ★ 一度も同意していない（null・空）は必ず要る。
 * ★ 言い方を直しただけの版に同意済みなら、取り直さない。
 * ★ 知らない版は【要る側】に倒す。
 */
export function needsConsent(savedVersion: string | null | undefined): boolean {
  if (typeof savedVersion !== 'string' || savedVersion.length === 0) return true;
  if (savedVersion === MEDIA_CONSENT_VERSION) return false;
  return !MEDIA_CONSENT_WORDING_ONLY.includes(savedVersion);
}

/** 監査ログや控えに残すための、文言の全文（1つの文字列）。 */
export function consentFullText(): string {
  return MEDIA_CONSENT_SECTIONS.map((s, i) => `${i + 1}. ${s.heading}\n${s.body}`).join('\n\n');
}

