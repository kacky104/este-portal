export const CONSENT_RECHECK_BADGE = '同意の取り直し';

/**
 * ★★★ 画面のいちばん上に出す帯。
 *
 * ★★ 【何が止まっているか】を先に書く。★ 「同意してください」だけでは、
 *   なぜ急にそれが要るのか・放っておくと何が起きるのかが読めない。
 * ★ サイト名は引数で受ける。★ 決め打ちにしない（増えた日に嘘になる）。
 * ★ 名前が読めないときは、名前のない言い方に倒す（嘘の名前を出さない）。
 */
export function consentRecheckNotice(siteLabels: readonly string[]): {
  title: string; body: string;
} {
  const names = siteLabels.filter((s) => typeof s === 'string' && s.length > 0);
  const where = names.length > 0 ? names.join('・') : 'いくつかのサイト';
  return {
    title: '同意の取り直しが必要です',
    body: `${where}へは、いま出勤も写メ日記も送っていません。接続テストも押せません。`
      + 'お預かりする情報の取り扱いをお読みのうえ、同意していただくと元どおり送るようになります。',
  };
}
