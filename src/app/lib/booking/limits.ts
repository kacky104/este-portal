// ★ 上限は【ネット予約（source='web'）だけを数えた200件】（2026-08-16 追加）。
//   予約ボードへの手入力（source='manual'）はこの一覧に出ないので、
//   手入力を何件足しても上限は減らない。手入力はボード側で全部見える。
//
// ★ getSalonBookings() の .limit() と、画面の「直近◯件まで表示しています」の文言が
//   この1か所から作られる。片方だけ変えると、実際の表示件数と案内文がズレる。
//
// ※ 一覧は slot_start の降順（予約日時が新しい順）なので、未来の予約が多いほど
//   過去の予約から先に一覧から外れる。「古い順に消えている」ように見えるのはこのため。
