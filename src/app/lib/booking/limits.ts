//   salon_bookings の行が自動で消えることは無い（保持期間・定期削除の仕組みは存在しない）。
//   行が実際に消えるのは以下の2つだけ:
//     1. オーナー（または運営）が画面から削除したとき（deleteBooking）
//     2. 同じ枠に残った status='cancelled' の行を、再予約のために掃除するとき
//        （UNIQUE(therapist_id, slot_start) 制約の回避。有効な予約は対象外）
//   201件目以降はDBに残ったまま、一覧に出てこないだけ。
