// エステ魂の写メ日記の状況（src/lib/esutamaDiaryStatus.ts）の自己点検（第141便・2026-09-04）。
//
// ★★★ ここで守りたいのは3つ。
//   ① 足して合わない表を出さない（人数の合計＝在籍）
//   ② 「送った」と「載った」を混ぜない・0件でも言葉にする
//   ③ ★ 分からないもの（相手の利用状況）を数に混ぜない＝「見込み」と書く
//
//   使い方:  npm run check:esutamadiarystatus

const path = require('path');
const S = require(path.join(__dirname, '..', '_tmpcheck', 'esutamaDiaryStatus.js'));

let fail = 0;
const eq = (name, got, want) => {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a !== b) { console.log('NG ' + name + '\n   got  ' + a + '\n   want ' + b); fail++; }
  else console.log('ok ' + name);
};
const base = {
  在籍: 23, 了承あり: 6, 了承あり結びあり: 1,
  送れた: 2, 送れていない: 0, 判定できず: 0, 最後に送れた: '2026-09-04T09:01:00Z',
};
const b = (o) => S.buildDiaryStatus({ ...base, ...o });

console.log('── 1. ★★★ 足して合わない表を出さない ──');
const r = b({});
eq('★ 送れる見込み', r.人.送れる見込み, 1);
eq('★ 了承がまだ', r.人.了承がまだ, 17);
eq('★ 名簿が未結び', r.人.名簿が未結び, 5);
// ★★★ 3つ足したら在籍と一致する。★ 合わない表を店舗様に見せない
eq('★★★ 合計は在籍と一致', r.人.送れる見込み + r.人.了承がまだ + r.人.名簿が未結び, 23);

console.log('\n── 2. ★★ おかしな数が来ても、おかしな表にしない ──');
// ★ 退職した方の記録が残っていても、在籍を超えない
eq('★★ 了承ありが在籍を超えない', b({ 了承あり: 99 }).人.了承がまだ, 0);
eq('★★ 結びありが了承ありを超えない', b({ 了承あり: 2, 了承あり結びあり: 99 }).人.送れる見込み, 2);
eq('★ 負の数は0として扱う', b({ 送れた: -5 }).送れた, 0);
eq('★ 在籍0でも落ちない', b({ 在籍: 0, 了承あり: 0, 了承あり結びあり: 0 }).人.在籍, 0);
eq('★ 在籍0なら合計も0',
   (() => { const x = b({ 在籍: 0, 了承あり: 0, 了承あり結びあり: 0 }).人;
     return x.送れる見込み + x.了承がまだ + x.名簿が未結び; })(), 0);

console.log('\n── 3. ★★★ 0件でも言葉にする ──');
// ★★★ 「送れる見込み」は0でも必ず出す（第35便の反省6）
eq('★★★ 見込み0でも数を出す', S.diaryStatusLine(b({ 了承あり結びあり: 0 })).startsWith('お送りできる見込み 0名'), true);
eq('★ 在籍の数は必ず出る', S.diaryStatusLine(r).includes('在籍 23名'), true);
// ★ 0のものは並べない（読む量を増やさない）
eq('★ 0のものは並べない',
   S.diaryStatusLine(b({ 了承あり: 23, 了承あり結びあり: 23 })).includes('ご了承がまだ'), false);
// ★★ 送信が1件も無いときは、空欄にせず言葉にする
eq('★★★ 1件も無ければ「まだお送りしていません」',
   S.diarySentLine(b({ 送れた: 0 })), 'まだお送りしていません');
// ★★ 「送れていない」は0でも出す（★ 見落とさせない）
eq('★★ 送れていない0でも出す', S.diarySentLine(r).includes('お送りできませんでした 0件'), true);
// ★★★ 「送った」と「載った」を混ぜない
eq('★★★ 「載りました」とは書かない', S.diarySentLine(r).includes('載り'), false);

console.log('\n── 4. ★★ 次にすることを出す（★ 無ければ黙る）──');
// ★ 何も問題が無ければ「異常なし」の行を作らない
eq('★ 問題が無ければ null', S.diaryNextStep(b({ 了承あり結びあり: 1 })), null);
// ★★★ 判定できないものが最優先（★ 二度と送らないので、人が見るしかない）
eq('★★★ 判定できずが最優先', S.diaryNextStep(b({ 判定できず: 1, 送れていない: 1 })).includes('掲載されているか'), true);
eq('★★ 送れていないは「自動でもう一度」と書く',
   S.diaryNextStep(b({ 送れていない: 1 })).includes('自動でもう一度'), true);
// ★ 送れる人が居ないときだけ、了承・結びの案内を出す
eq('★ 誰も了承していなければ、了承の案内',
   S.diaryNextStep(b({ 了承あり: 0, 了承あり結びあり: 0 })).includes('エステ魂へ送ってよい'), true);
// ★★★ 順番: 「了承はもらったのに結びが無い」を先に出す（★ あと1手で送れる）
eq('★★★ 了承済みが居て結びが無ければ、結びの案内が先',
   S.diaryNextStep(b({ 了承あり: 6, 了承あり結びあり: 0 })).includes('結びつけて'), true);
eq('★★ そのときは「ご了承をいただいた方がいます」と書く',
   S.diaryNextStep(b({ 了承あり: 6, 了承あり結びあり: 0 })).includes('ご了承をいただいた方がいます'), true);

console.log('\n── 5. ★★★ 分からないものを数に混ぜない ──');
// ★★ 相手の利用状況は見ていない。★ だから「送れます」と言い切らない
eq('★★★ 「見込み」と書く', S.diaryStatusLine(r).includes('見込み'), true);
eq('★★★ 「送れます」と言い切らない', S.diaryStatusLine(r).includes('お送りできます'), false);

console.log(fail === 0 ? '\n★ すべて通りました' : '\n' + fail + ' 件 通りませんでした');
process.exit(fail === 0 ? 0 : 1);
