// 出勤枠の時刻（src/app/lib/booking/slots.ts の scheduleWindowUtc）の自己点検（第1408便・2026-10-12）。
//
// ★★★ ここで見張っているのは:
//   開始が朝6時より前（00:00〜05:30）の出勤は、出勤日の【翌日】の時刻として読むこと。
//   出勤の入力（コネックエフ・マイページ）は開始を「06:00〜翌05:30」から選ぶ＝土曜の欄の「00:00」は日曜 0:00。
//   ★ 暦日のまま読むと、フクエスCRM・ネット予約のどの日にも出なくなる（ラビリンス様 みつは様 10/17 00:00〜05:00）。
//
//   使い方:  npm run check:schedulewindow

const path = require('path');
const m = require(path.join(__dirname, '..', '_tmpcheck', 'app', 'lib', 'booking', 'slots.js'));
const f = require(path.join(__dirname, '..', '_tmpcheck', 'lib', 'scheduleFormat.js'));

let fail = 0;
const eq = (name, got, want) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g !== w) { console.log('NG ' + name + '\n   got  ' + g + '\n   want ' + w); fail++; }
  else console.log('ok ' + name);
};
const w = (d, s, e) => { const r = m.scheduleWindowUtc(d, s, e); return [r.startUtc.toISOString(), r.endUtc.toISOString()]; };
// 日本時間 → UTC の ISO
const j = (d, hm) => new Date(`${d}T${hm}:00+09:00`).toISOString();

eq('昼の出勤（14:30〜19:30）は同じ日', w('2026-10-17', '14:30', '19:30'), [j('2026-10-17', '14:30'), j('2026-10-17', '19:30')]);
eq('夜跨ぎ（21:00〜翌03:00）は終わりだけ翌日', w('2026-10-17', '21:00', '03:00'), [j('2026-10-17', '21:00'), j('2026-10-18', '03:00')]);
eq('★★★ 開始 00:00（〜05:00）は翌日の 0:00〜5:00（10/17 の欄 → 10/18）', w('2026-10-17', '00:00', '05:00'), [j('2026-10-18', '00:00'), j('2026-10-18', '05:00')]);
eq('★ 開始 05:30（〜08:00）も翌日', w('2026-10-17', '05:30', '08:00'), [j('2026-10-18', '05:30'), j('2026-10-18', '08:00')]);
eq('★ 開始 06:00 ちょうどは同じ日（区切り）', w('2026-10-17', '06:00', '12:00'), [j('2026-10-17', '06:00'), j('2026-10-17', '12:00')]);
eq('★ 開始 01:00〜終わり 00:30（ほぼ24時間）は 翌1:00〜翌々0:30', w('2026-10-17', '01:00', '00:30'), [j('2026-10-18', '01:00'), j('2026-10-19', '00:30')]);
eq('月をまたぐ（10/31 の 00:00〜05:00 → 11/1）', w('2026-10-31', '00:00', '05:00'), [j('2026-11-01', '00:00'), j('2026-11-01', '05:00')]);
eq('区切りの値は朝6時', m.SCHEDULE_DAY_START_MIN, 360);

// ★★ 第1409便: 表示の「翌」も同じ決め方（朝6時より前の開始は開始にも「翌」）
eq('表示: 昼・夜跨ぎ・0時開始・5:30開始・6:00開始', [
  f.shiftRangeText('14:30', '19:30'), f.shiftRangeText('21:00', '03:00'), f.shiftRangeText('00:00', '05:00'),
  f.shiftRangeText('05:30', '08:00'), f.shiftRangeText('06:00', '12:00'), f.shiftRangeText('20:30', '00:30', '-'),
], ['14:30〜19:30', '21:00〜翌03:00', '翌00:00〜翌05:00', '翌05:30〜翌08:00', '06:00〜12:00', '20:30-翌00:30']);
eq('表示（H:MM 形）: 0時開始・夜跨ぎ', [f.buildDisplayHours('00:00', '05:00'), f.buildDisplayHours('21:00', '03:00')], ['翌0:00〜翌5:00', '21:00〜翌3:00']);

console.log(fail === 0 ? '\n全部 ok' : '\nNG ' + fail + ' 件');
process.exit(fail === 0 ? 0 : 1);
