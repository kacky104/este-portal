--
-- ── 何を足すか ─────────────────────────────────────
-- 1. salon_sites.contact_email … フォームの通知先メール（店舗が /hp/{slug}/admin「お問い合わせ」で入れる）
-- 2. hp_contacts              … 送信された問い合わせの控え（メールが届かなくても消えない）
--
-- フォームの ON/OFF と案内文は salon_sites.blocks（jsonb）の blocks.contact に入れる＝列は要らない。
--
-- ── contact_email を blocks に入れない理由 ──────────
-- blocks は公開ページが anon で読む列（列単位 grant 済み）。メールアドレスを入れると
-- PostgREST を直接叩けば誰でも読める。別の列にして【anon / authenticated には grant しない】。
-- 読むのは service_role だけ（管理画面 resolveAccess・送信アクション）。
-- ★★ だから lib/hpSite.ts の HP_SITE_COLUMNS には【絶対に足さない】。足すと anon の select が
--   「権限が無い」で落ちて全店の HP が表示できなくなる（第21便で起きた事故と同型）。

alter table public.salon_sites
  add column if not exists contact_email text;

comment on column public.salon_sites.contact_email is
  '公式HPのお問い合わせフォームの通知先メール。null/空=フォームを出さない。anon には grant しない（service_role だけが読む）';

-- 問い合わせの控え。INSERT は service_role（サーバーアクション）だけ。公開ポリシーは持たせない
-- （hp_inquiries・listing_inquiries と同じ作法＝PostgREST 直叩きのスパム遮断）。
create table if not exists public.hp_contacts (
  id          bigint generated by default as identity primary key,
  salon_id    bigint not null references public.salons(id) on delete cascade,
  name        text not null,
  email       text not null,
  tel         text,
  subject     text not null,          -- 'service' | 'recruit' | 'booking' | 'other'（正は lib/hp/contact.ts）
  body        text not null,
  sent_to     text,                   -- 送信時点の通知先（あとで通知先を変えても記録が残る）
  mail_error  text,                   -- Resend のエラー文。null=送れた
  created_at  timestamptz not null default now()
);

comment on table public.hp_contacts is '公式HP（フクエスサイト）のお問い合わせフォームから送られた内容の控え（第1717便）';

create index if not exists hp_contacts_salon_created_idx on public.hp_contacts (salon_id, created_at desc);

alter table public.hp_contacts enable row level security;
-- ポリシーは作らない＝anon / authenticated からは一切見えない・書けない。service_role は RLS を素通りする。
revoke all on table public.hp_contacts from anon, authenticated;

